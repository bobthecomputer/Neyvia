"""Compile exact, source-bound CL startup context without runtime downloads."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # A build may use an already-cached exact tokenizer, never a network fetch.
    def offline(event, values):
        if event in {"socket.connect", "socket.bind", "socket.getaddrinfo"}:
            raise PermissionError("CL context compilation requires local tokenizer data")
    sys.addaudithook(offline)
    from grant_agent.neyvia_manuals import records
    from grant_agent.cl.tokens import count_tokens
    descriptors = [{"id": r["id"], "description": r["description"]} for r in records()]
    primer = (REPO / "docs/standard/1.1/primer.md").read_text(encoding="utf-8").strip()
    primer_count = count_tokens(primer)
    if primer_count > 300:
        raise ValueError("CL 1.1 R16: primer exceeds 300 tokens")
    lines, counts = [], []
    for row in descriptors:
        words = row["description"].replace("\n", " ").split()
        prefix = "L " + ("cua" if row["id"] == "computer-use" else row["id"]) + " v2 -- "
        while words and count_tokens(prefix + " ".join(words)) > 20:
            words.pop()
        line = prefix + " ".join(words)
        count = count_tokens(line)
        if count > 20:
            raise ValueError("CL manual identifier alone exceeds the index token limit: " + row["id"])
        lines.append(line)
        counts.append(count)
    descriptor_bytes = json.dumps(descriptors, sort_keys=True, ensure_ascii=True, separators=(",", ":")).encode()
    values = {
        "PRIMER_O200K_SHA256": hashlib.sha256(primer.encode()).hexdigest(),
        "PRIMER_O200K_TOKENS": primer_count,
        "MANUAL_DESCRIPTIONS_SHA256": hashlib.sha256(descriptor_bytes).hexdigest(),
        "INDEX_LINES": tuple(lines), "INDEX_O200K_TOKENS": tuple(counts),
    }
    rendered = '"""Generated by scripts/build_cl_context.py; exact local o200k measurements."""\n'
    rendered += "\n".join(name + " = " + repr(value) for name, value in values.items()) + "\n"
    target = REPO / "src/grant_agent/cl/measured_context.py"
    if args.check:
        if target.read_text(encoding="utf-8") != rendered:
            raise ValueError("CL measured context is stale; run scripts/build_cl_context.py")
    else:
        target.write_text(rendered, encoding="utf-8", newline="\n")
    print(json.dumps({"ok": True, "check": args.check, "primerTokens": primer_count,
                      "manuals": len(lines), "maximumIndexTokens": max(counts, default=0)}))


if __name__ == "__main__":
    main()
