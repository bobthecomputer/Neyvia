#!/usr/bin/env python3
"""Finish CLIProxyAPI bring-up + OAuth attempt on the NAS runtime host."""

from __future__ import annotations

import json
import re
import time
from datetime import datetime, timezone
from pathlib import Path

import paramiko

ROOT = Path(__file__).resolve().parents[1]
CREDENTIALS_PATH = ROOT / ".agent_control" / "nas_codex2_100_125_54_118.json"
RECEIPT_DIR = ROOT / ".agent_control" / "nas_transfers"
RUNTIME = "/volume1/Saclay/runtime"
PORT = 8317


def _utc_stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def main() -> int:
    RECEIPT_DIR.mkdir(parents=True, exist_ok=True)
    stamp = _utc_stamp()
    receipt_path = RECEIPT_DIR / f"nas_cliproxyapi_finish_{stamp}.json"
    creds = json.loads(CREDENTIALS_PATH.read_text(encoding="utf-8"))
    client = paramiko.SSHClient()
    client.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    client.connect(
        hostname=creds.get("host", "192.0.2.10"),
        port=int(creds.get("port", 22)),
        username=creds.get("username") or creds.get("user") or "nas-user",
        password=creds.get("password") or creds.get("secret") or "",
        look_for_keys=False,
        allow_agent=False,
        timeout=20,
    )

    def run(cmd: str, timeout: int = 120) -> dict:
        started = time.time()
        _stdin, stdout, stderr = client.exec_command(cmd, timeout=timeout)
        out = stdout.read().decode("utf-8", "replace")
        err = stderr.read().decode("utf-8", "replace")
        code = stdout.channel.recv_exit_status()
        return {
            "command": cmd[:700],
            "exitCode": code,
            "stdout": out[-20000:],
            "stderr": err[-4000:],
            "elapsedSec": round(time.time() - started, 2),
        }

    receipt: dict = {
        "createdAt": datetime.now(timezone.utc).isoformat(),
        "goal": "Finish CLIProxyAPI start + Codex OAuth for claudex",
        "proxyPort": PORT,
        "proxyUrl": f"http://127.0.0.1:{PORT}",
        "anthropicBaseUrl": f"http://127.0.0.1:{PORT}",
        "steps": [],
        "oauth": {"status": "not_started"},
        "status": "started",
        "openCodeGoNote": "OpenCodeGo auth left untouched.",
    }

    # Read existing token from config if present.
    cfg = run(f"cat {RUNTIME}/cliproxyapi/config.yaml")
    receipt["steps"].append({"name": "read_config", **cfg})
    token_match = re.search(r'api-keys:\s*\n\s*-\s*"([^"]+)"', cfg.get("stdout") or "")
    api_token = token_match.group(1) if token_match else ""
    receipt["apiTokenEnv"] = "CLIPROXY_API_KEY"

    # Free port and restart cleanly.
    kill = run(
        f"pkill -f '{RUNTIME}/bin/cli-proxy-api' || true; "
        f"fuser -k {PORT}/tcp 2>/dev/null || true; "
        "sleep 1; "
        f"ss -ltnp 2>/dev/null | grep ':{PORT}' || netstat -ltn 2>/dev/null | grep ':{PORT}' || echo 'port-free'"
    )
    receipt["steps"].append({"name": "free_port", **kill})

    start = run(
        f"mkdir -p {RUNTIME}/home/.cli-proxy-api {RUNTIME}/cliproxyapi; "
        f"export HOME={RUNTIME}/home; "
        f"export PATH={RUNTIME}/bin:$PATH; "
        f"nohup {RUNTIME}/bin/cli-proxy-api -config {RUNTIME}/cliproxyapi/config.yaml "
        f">> {RUNTIME}/cliproxyapi/cliproxyapi.log 2>&1 & echo $! > {RUNTIME}/cliproxyapi/cliproxyapi.pid; "
        "sleep 2; "
        f"cat {RUNTIME}/cliproxyapi/cliproxyapi.pid; "
        f"ps -p $(cat {RUNTIME}/cliproxyapi/cliproxyapi.pid) -o pid,cmd || true; "
        f"curl -s -o /tmp/cpa_health.body -w '%{{http_code}}' http://127.0.0.1:{PORT}/ || true; "
        "echo; head -c 200 /tmp/cpa_health.body 2>/dev/null; echo"
    )
    receipt["steps"].append({"name": "restart_proxy", **start})
    listening = "200" in (start.get("stdout") or "") or "API server started" in (
        run(f"tail -n 30 {RUNTIME}/cliproxyapi/cliproxyapi.log").get("stdout") or ""
    )

    # Persist runtime env overlay (Claude proxy route; not Anthropic classic login).
    if api_token:
        env_write = run(
            "umask 077; "
            f"printf '%s\\n' "
            f"'# Generated by nas_finish_cliproxyapi.py' "
            f"'CLIPROXY_API_KEY={api_token}' "
            f"'ANTHROPIC_AUTH_TOKEN={api_token}' "
            f"'ANTHROPIC_BASE_URL=http://127.0.0.1:{PORT}' "
            f"'CLAUDE_CODE_SUBAGENT_MODEL=gpt-5.6-sol' "
            f"'CLAUDE_CODE_ALWAYS_ENABLE_EFFORT=1' "
            f"'CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY=1' "
            f"'FLUXIO_HARNESS_COMPAT=cliproxy' "
            f"> {RUNTIME}/home/.fluxio_cliproxy_env; "
            f"ls -la {RUNTIME}/home/.fluxio_cliproxy_env"
        )
        receipt["steps"].append({"name": "write_runtime_env", **env_write})
        local_env = ROOT / ".agent_control" / "cliproxy_local.env"
        local_env.write_text(
            "\n".join(
                [
                    f"CLIPROXY_PORT={PORT}",
                    f"CLIPROXY_API_KEY={api_token}",
                    f"ANTHROPIC_AUTH_TOKEN={api_token}",
                    f"ANTHROPIC_BASE_URL=http://127.0.0.1:{PORT}",
                    "CLAUDE_CODE_SUBAGENT_MODEL=gpt-5.6-sol",
                    "CLAUDE_CODE_ALWAYS_ENABLE_EFFORT=1",
                    "CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY=1",
                    "FLUXIO_HARNESS_COMPAT=cliproxy",
                    "",
                ]
            ),
            encoding="utf-8",
        )
        receipt["localEnvFile"] = str(local_env.as_posix())

    # Prefer reuse of existing Neyvia OpenAI Codex OAuth tokens (NOT device-code).
    # Device-code / signing-letter login is deprecated for this project.
    seed_hint = run(
        f"ls -la {RUNTIME}/home/.codex/auth.json {RUNTIME}/home/.cli-proxy-api 2>/dev/null || true; "
        f"test -f {RUNTIME}/home/.codex/auth.json && echo HAS_CODEX_AUTH || echo NO_CODEX_AUTH"
    )
    receipt["steps"].append({"name": "probe_existing_codex_oauth", **seed_hint})

    oauth_login = run(
        f"export HOME={RUNTIME}/home; export PATH={RUNTIME}/bin:$PATH; "
        f"cd {RUNTIME}/cliproxyapi; "
        f"timeout 25 {RUNTIME}/bin/cli-proxy-api -config {RUNTIME}/cliproxyapi/config.yaml "
        f"-codex-login -no-browser 2>&1 || true",
        timeout=40,
    )
    receipt["steps"].append({"name": "codex_oauth_no_browser", **oauth_login})

    auth_ls = run(
        f"ls -la {RUNTIME}/home/.cli-proxy-api 2>/dev/null; "
        f"find {RUNTIME}/home/.cli-proxy-api -maxdepth 2 -type f 2>/dev/null | head -50"
    )
    receipt["steps"].append({"name": "auth_dir", **auth_ls})
    has_auth = bool(re.search(r"\.json\b", auth_ls.get("stdout") or "", re.I))

    urls = re.findall(r"https?://[^\s\"']+", oauth_login.get("stdout") or "")
    # Prefer authorize URL; ignore any accidental device URLs.
    authorize_urls = [u for u in urls if "oauth/authorize" in u or "localhost:1455" in u]

    if has_auth:
        receipt["oauth"] = {"status": "completed_or_present", "authFilesPresent": True}
    else:
        receipt["oauth"] = {
            "status": "needs_browser_or_seed",
            "authFilesPresent": False,
            "authMethod": "OpenAI Codex OAuth (browser redirect / token reuse)",
            "deprecated": "device-code / -codex-device-login / signing letters",
            "loginUrls": authorize_urls[:4] or urls[:4],
            "operatorSteps": [
                "Proxy binary is installed at /volume1/Saclay/runtime/bin/cli-proxy-api and should be listening on 8317.",
                "Complete ChatGPT/Codex OAuth the Neyvia way (NOT device-code, NOT `claude auth login`):",
                "",
                "Preferred — reuse existing Fluxio/Neyvia OpenAI Codex OAuth tokens:",
                "  python scripts/nas_seed_cliproxy_from_codex_oauth.py",
                "",
                "Fallback — browser redirect + callback tunnel (same OAuth as Fluxio):",
                f"  ssh -L 1455:127.0.0.1:1455 nas-user@{creds.get('host')}",
                f"  export HOME={RUNTIME}/home PATH={RUNTIME}/bin:$PATH",
                f"  cli-proxy-api -config {RUNTIME}/cliproxyapi/config.yaml -codex-login",
                "  1. Open the printed OpenAI authorize URL",
                "  2. Sign in with the ChatGPT/Codex subscription account",
                "  3. Pick the correct workspace if asked",
                "  4. Approve access",
                "  5. Wait for localhost:1455 success page",
                "",
                "Then verify:",
                f"  curl -s http://127.0.0.1:{PORT}/v1/models -H \"Authorization: Bearer $CLIPROXY_API_KEY\"",
                "Neyvia profile id: claude-code-claudex",
                "Windows wrappers: scripts/claudex.cmd and scripts/claudex.ps1",
            ],
        }

    health = run(
        f"curl -s -o /tmp/cpa_health2.body -w '%{{http_code}}' http://127.0.0.1:{PORT}/ || true; echo; "
        f"curl -s http://127.0.0.1:{PORT}/v1/models -H 'Authorization: Bearer {api_token}' | head -c 400; echo; "
        f"tail -n 20 {RUNTIME}/cliproxyapi/cliproxyapi.log"
    )
    receipt["steps"].append({"name": "health_and_models", **health})
    receipt["listening"] = listening or ("200" in (health.get("stdout") or ""))
    receipt["neyviaLaunch"] = {
        "harnessProfileId": "claude-code-claudex",
        "ANTHROPIC_BASE_URL": f"http://127.0.0.1:{PORT}",
        "CLAUDE_CODE_SUBAGENT_MODEL": "gpt-5.6-sol",
        "windowsWrapper": ["scripts/claudex.cmd", "scripts/claudex.ps1"],
        "docs": "docs/CLIPROXYAPI_CLAUDEX.md",
    }
    receipt["status"] = "installed" if receipt.get("listening") else "partial"
    client.close()
    receipt_path.write_text(json.dumps(receipt, indent=2), encoding="utf-8")
    # Avoid dumping token in stdout summary
    summary = {k: v for k, v in receipt.items() if k != "apiTokenBootstrap"}
    print(json.dumps(summary, indent=2))
    print(f"receipt={receipt_path}")
    return 0 if receipt["status"] == "installed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
